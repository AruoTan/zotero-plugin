#!/usr/bin/env bash
# Bundle the source into a Zotero plugin without a JavaScript toolchain.
set -euo pipefail

PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
DIST_DIR="$PROJECT_DIR/dist"
mkdir -p "$DIST_DIR"
BUILD_DIR="$(mktemp -d "${TMPDIR:-/tmp}/zotero-plugin-build.XXXXXX")"
trap 'rm -rf -- "$BUILD_DIR"' EXIT

mkdir -p "$BUILD_DIR/assets/fonts"
mkdir -p "$BUILD_DIR/vendor/mathjax"
cp "$PROJECT_DIR/vendor/mathjax/LICENSE" "$BUILD_DIR/vendor/mathjax/LICENSE"
cp "$PROJECT_DIR/assets/fonts/HetangYuese-NOTICE.txt" "$BUILD_DIR/assets/fonts/HetangYuese-NOTICE.txt"
cp "$PROJECT_DIR/manifest.json" "$BUILD_DIR/manifest.json"
FONT_FILES=("HetangYuese-Regular.ttf")
FONT_FAMILIES=("ZoteroPluginHandwriting")
{
  printf '/* Generated by scripts/build.sh. Edit files in src/ instead. */\n\n'
  # Use one handwriting face for Chinese, English, and digits.
  # Embed it so every reader document can load it offline.
  printf 'var ZoteroPluginHandwritingFonts = [\n'
  for index in "${!FONT_FILES[@]}"; do
    printf '  { family: "%s", source: "data:font/ttf;base64,' "${FONT_FAMILIES[$index]}"
    base64 < "$PROJECT_DIR/assets/fonts/${FONT_FILES[$index]}" | tr -d '\n'
    printf '" },\n'
  done
  printf '];\n\n'
  cat "$PROJECT_DIR/vendor/mathjax/tex-svg.js"
  printf '\n'
  # Keep feature modules before the lifecycle entry point.
  cat "$PROJECT_DIR/src/features/selection-popup.js"
  printf '\n'
  cat "$PROJECT_DIR/src/features/handwritten-text.js"
  printf '\n'
  cat "$PROJECT_DIR/src/features/black-text-sidebar-filter.js"
  printf '\n'
  cat "$PROJECT_DIR/src/features/annotation-hit-targets.js"
  printf '\n'
  cat "$PROJECT_DIR/src/features/math-text.js"
  printf '\n'
  cat "$PROJECT_DIR/src/features/text-annotation-size.js"
  printf '\n'
  cat "$PROJECT_DIR/src/features/sidebar-annotation-navigation.js"
  printf '\n'
  cat "$PROJECT_DIR/src/features/library-tag-filter.js"
  printf '\n'
  cat "$PROJECT_DIR/src/bootstrap.js"
} > "$BUILD_DIR/bootstrap.js"

(
  cd "$BUILD_DIR"
  zip -q zotero-plugin.xpi manifest.json bootstrap.js assets/fonts/HetangYuese-NOTICE.txt vendor/mathjax/LICENSE
)
mv -f "$BUILD_DIR/zotero-plugin.xpi" "$DIST_DIR/zotero-plugin.xpi"
printf 'Built %s\n' "$DIST_DIR/zotero-plugin.xpi"
